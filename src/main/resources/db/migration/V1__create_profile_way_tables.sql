
CREATE TABLE profile_profiles (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  email VARCHAR(255) NOT NULL UNIQUE,
                                  status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
                                  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                  CONSTRAINT chk_profile_status
                                      CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED'))
);

CREATE TABLE profile_publishers (
                                    id BIGINT PRIMARY KEY,
                                    first_name VARCHAR(100) NOT NULL,
                                    last_name VARCHAR(100) NOT NULL,
                                    niche VARCHAR(30) NOT NULL,
                                    bio TEXT,
                                    country VARCHAR(100),

                                    CONSTRAINT fk_publisher_profile
                                        FOREIGN KEY (id) REFERENCES profile_profiles(id),

                                    CONSTRAINT chk_publisher_niche
                                        CHECK (niche IN (
                                                         'BEAUTY', 'TECH', 'GAMING', 'TRAVEL',
                                                         'LIFESTYLE', 'FOOD', 'SPORT'
                                            ))
);

CREATE TABLE profile_advertisers (
                                     id BIGINT PRIMARY KEY,
                                     company_name VARCHAR(255) NOT NULL,
                                     sector VARCHAR(150) NOT NULL,
                                     website VARCHAR(255),

                                     CONSTRAINT fk_advertiser_profile
                                         FOREIGN KEY (id) REFERENCES profile_profiles(id)
);
