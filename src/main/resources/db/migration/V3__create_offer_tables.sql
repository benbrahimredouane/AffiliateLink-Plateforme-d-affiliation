CREATE TABLE offer_offers (
                              id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                              advertiser_id BIGINT NOT NULL,            -- deliberately NO foreign key to profile tables
                              title         VARCHAR(255)  NOT NULL,
                              description   TEXT          NOT NULL,
                              landing_url   VARCHAR(2048) NOT NULL,
                              niche         VARCHAR(30)   NOT NULL,
                              created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,

                              CONSTRAINT chk_offer_niche
                                  CHECK (niche IN ('BEAUTY','TECH','GAMING','TRAVEL','LIFESTYLE','FOOD','SPORT'))
);

CREATE TABLE offer_campaigns (
                                 id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                 offer_id     BIGINT        NOT NULL,
                                 name         VARCHAR(255)  NOT NULL,
                                 start_date   DATE          NOT NULL,
                                 end_date     DATE          NOT NULL,
                                 budget       NUMERIC(12,2) NOT NULL,
                                 payout_model VARCHAR(20)   NOT NULL,
                                 payout_value NUMERIC(10,2) NOT NULL,
                                 status       VARCHAR(20)   NOT NULL DEFAULT 'DRAFT',

                                 CONSTRAINT fk_campaign_offer FOREIGN KEY (offer_id) REFERENCES offer_offers(id),
                                 CONSTRAINT chk_campaign_dates  CHECK (end_date > start_date),
                                 CONSTRAINT chk_campaign_budget CHECK (budget > 0),
                                 CONSTRAINT chk_campaign_status CHECK (status IN ('DRAFT','ACTIVE','PAUSED','ENDED')),
                                 CONSTRAINT chk_campaign_payout_model
                                     CHECK (payout_model IN ('CPC','CPL','CPA_FIXED','CPA_PERCENT')),
                                 CONSTRAINT chk_campaign_payout_value
                                     CHECK (payout_value > 0 AND (payout_model <> 'CPA_PERCENT' OR payout_value <= 100))
);

CREATE TABLE offer_tags (
                            id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            name VARCHAR(50) NOT NULL UNIQUE,
                            CONSTRAINT chk_tag_lowercase CHECK (name = lower(name))
);

CREATE TABLE offer_offer_tags (
                                  offer_id BIGINT NOT NULL REFERENCES offer_offers(id),
                                  tag_id   BIGINT NOT NULL REFERENCES offer_tags(id),
                                  PRIMARY KEY (offer_id, tag_id)
);

CREATE INDEX idx_offer_advertiser ON offer_offers (advertiser_id);
CREATE INDEX idx_offer_niche      ON offer_offers (niche);
CREATE INDEX idx_campaign_offer   ON offer_campaigns (offer_id);
CREATE INDEX idx_campaign_status  ON offer_campaigns (status);

CREATE UNIQUE INDEX uq_one_active_campaign_per_offer
    ON offer_campaigns (offer_id) WHERE status = 'ACTIVE';